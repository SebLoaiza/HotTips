import {
    formatMoney,
    formatNumber
} from "../utils/formatters.js";


export function exportTipDistributionCSV(
    tipDistribution
) {


    const rows = [];


    // =========================
    // DATE / TIME
    // =========================


    const now =
        new Date();


    const dateTime =
        `${String(
            now.getMonth() + 1
        ).padStart(2, "0")}-` +

        `${String(
            now.getDate()
        ).padStart(2, "0")}-` +

        `${now.getFullYear()} ` +

        `${String(
            now.getHours()
        ).padStart(2, "0")}` +

        `${String(
            now.getMinutes()
        ).padStart(2, "0")}` +

        `${String(
            now.getSeconds()
        ).padStart(2, "0")}`;


    // =========================
    // TITLE
    // =========================


    rows.push([
        "HotTips Distribution History"
    ]);


    rows.push([
        `Generated: ${dateTime}`
    ]);


    rows.push([
        ""
    ]);


    // =========================
    // KEY
    // =========================


    rows.push([
        "KEY"
    ]);


    rows.push([
        "Date",
        "Date of the meal shift"
    ]);


    rows.push([
        "Meal",
        "Breakfast, Lunch, or Dinner"
    ]);


    rows.push([
        "Employee",
        "Employee name"
    ]);


    rows.push([
        "Role",
        "Employee's assigned role"
    ]);


    rows.push([
        "Cash Drop",
        "Cash drop entered for the employee"
    ]);


    rows.push([
        "Cash Sales",
        "Employee's cash sales"
    ]);


    rows.push([
        "Credit Card Sales",
        "Employee's credit card sales"
    ]);


    rows.push([
        "Total Sales",
        "Cash Sales + Card Sales"
    ]);


    rows.push([
        "Pre-Distributed Cash Tips",
        "Cash tips generated by employee"
    ]);


    rows.push([
        "Toast Credit Card Tips",
        "Credit card tips generated by employee (pulled from Toast)"
    ]);


    rows.push([
        "Pre-Distributed Total Tips",
        "Pre-Distributed Cash Tips + Toast Credit Card Tips"
    ]);


    rows.push([
        "Cash Tips Kept",
        "Cash tips kept after their tips get split"
    ]);


    rows.push([
        "Credit Card Tips Kept",
        "Credit Card tips kept after their tips get split"
    ]);


    rows.push([
        "Pool Cash Tips Received",
        "Cash tips received from the tip pool"
    ]);


    rows.push([
        "Pool Credit Card Tips Received",
        "Credit card tips received from the tip pool"
    ]);


    rows.push([
        "Cash Payout",
        "Cash Tips Kept + Pool Cash Tips Received"
    ]);


    rows.push([
        "Credit Card Payout",
        "Credit Card Tips Kept + Pool Credit Card Tips Received"
    ]);


    rows.push([
        "Total Payout",
        "Cash Payout + Credit Card Payout"
    ]);


    rows.push([
        "Sales / Hr",
        "Total Sales divided by hours worked"
    ]);


    rows.push([
        "Orders / Hr",
        "Orders divided by hours worked"
    ]);


    rows.push([
        "Tips / Hr",
        "Pre-Distributed Total Tips divided by hours worked"
    ]);


    rows.push([
        "Avg Tip / Order",
        "Pre-Distributed Total Tips divided by orders"
    ]);


    rows.push([
        "Worked Minutes",
        "Total minutes worked"
    ]);


    rows.push([
        "Hours",
        "Worked Minutes divided by 60"
    ]);


    rows.push([
        "Orders",
        "Number of orders"
    ]);


    // =========================
    // SEPARATOR
    // =========================


    rows.push([
        ""
    ]);


    rows.push([
        ""
    ]);


    // =========================
    // DATA HEADER
    // =========================


    rows.push([

        "Date",
        "Meal",

        "Employee",
        "Role",

        // -------------------------
        // CASH DROP
        // -------------------------

        "Cash Drop",

        // -------------------------
        // SALES
        // -------------------------

        "Cash Sales",
        "Credit Card Sales",
        "Total Sales",

        // -------------------------
        // ORIGINAL TIPS
        // -------------------------

        "Pre-Distributed Cash Tips",
        "Toast Credit Card Tips",
        "Pre-Distributed Total Tips",

        // -------------------------
        // DISTRIBUTION
        // -------------------------

        "Cash Tips Kept",
        "Credit Card Tips Kept",

        "Pool Cash Tips Received",
        "Pool Credit Card Tips Received",

        "Cash Payout",
        "Credit Card Payout",
        "Total Payout",

        // -------------------------
        // STATS
        // -------------------------

        "Sales / Hr",
        "Orders / Hr",
        "Tips / Hr",
        "Avg Tip / Order",

        // -------------------------
        // WORK
        // -------------------------

        "Worked Minutes",
        "Hours",
        "Orders"

    ]);


    // =========================
    // BUILD DATA ROWS
    // =========================


    for (
        const block of tipDistribution
    ) {


        for (
            const employee of block.employees
        ) {


            // =========================
            // CASH DROP
            // =========================


            const cashDrop =
                employee.cash_drop ?? 0;


            // =========================
            // SALES
            // =========================


            const cashSales =
                employee.cash_sales ?? 0;


            const cardSales =
                employee.card_sales ?? 0;


            const totalSales =
                cashSales +
                cardSales;


            // =========================
            // ORIGINAL TIPS
            // =========================


            const cashTips =
                employee.cash_tips ?? 0;


            const cardTips =
                employee.card_tips ?? 0;


            const totalOriginalTips =
                cashTips +
                cardTips;


            // =========================
            // DISTRIBUTION
            // =========================


            const cashKept =
                employee.cash_kept ?? 0;


            const cardKept =
                employee.card_kept ?? 0;


            const poolCashReceived =
                employee.pool_cash_received ?? 0;


            const poolCardReceived =
                employee.pool_card_received ?? 0;


            const cashPayout =
                cashKept +
                poolCashReceived;


            const cardPayout =
                cardKept +
                poolCardReceived;


            const totalPayout =
                cashPayout +
                cardPayout;


            // =========================
            // WORK TIME
            // =========================


            const workedMinutes =
                employee.worked_minutes ?? 0;


            const hours =
                employee.hours ??
                (
                    workedMinutes / 60
                );


            // =========================
            // STATS
            // =========================


            const salesPerHour =
                hours > 0
                    ?
                    totalSales / hours
                    :
                    0;


            const orders =
                employee.order_count ?? 0;


            const ordersPerHour =
                hours > 0
                    ?
                    orders / hours
                    :
                    0;


            const tipsPerHour =
                hours > 0
                    ?
                    totalOriginalTips / hours
                    :
                    0;


            const avgTipPerOrder =
                orders > 0
                    ?
                    totalOriginalTips / orders
                    :
                    0;


            // =========================
            // ADD DATA ROW
            // =========================


            rows.push([

                block.date,

                block.meal,

                employee.name,

                employee.role,

                // -------------------------
                // CASH DROP
                // -------------------------

                formatMoney(
                    cashDrop
                ),

                // -------------------------
                // SALES
                // -------------------------

                formatMoney(
                    cashSales
                ),

                formatMoney(
                    cardSales
                ),

                formatMoney(
                    totalSales
                ),

                // -------------------------
                // ORIGINAL TIPS
                // -------------------------

                formatMoney(
                    cashTips
                ),

                formatMoney(
                    cardTips
                ),

                formatMoney(
                    totalOriginalTips
                ),

                // -------------------------
                // DISTRIBUTION
                // -------------------------

                formatMoney(
                    cashKept
                ),

                formatMoney(
                    cardKept
                ),

                formatMoney(
                    poolCashReceived
                ),

                formatMoney(
                    poolCardReceived
                ),

                formatMoney(
                    cashPayout
                ),

                formatMoney(
                    cardPayout
                ),

                formatMoney(
                    totalPayout
                ),

                // -------------------------
                // STATS
                // -------------------------

                formatMoney(
                    salesPerHour
                ),

                formatNumber(
                    ordersPerHour
                ),

                formatMoney(
                    tipsPerHour
                ),

                formatMoney(
                    avgTipPerOrder
                ),

                // -------------------------
                // WORK
                // -------------------------

                workedMinutes,

                formatNumber(
                    hours
                ),

                orders

            ]);


        }


    }


    // =========================
    // DOWNLOAD
    // =========================


    downloadCSV(
        rows,
        `HotTips Dist History - ${dateTime}.csv`
    );


}


// =========================
// CSV CREATION
// =========================


function downloadCSV(
    rows,
    filename
) {


    const csv =
        rows
        .map(
            row =>
                row
                .map(
                    value =>
                        `"${String(
                            value ?? ""
                        ).replaceAll(
                            '"',
                            '""'
                        )}"`
                )
                .join(",")
        )
        .join("\n");


    const blob =
        new Blob(
            [
                csv
            ],
            {
                type:
                    "text/csv;charset=utf-8;"
            }
        );


    const url =
        URL.createObjectURL(
            blob
        );


    const link =
        document.createElement(
            "a"
        );


    link.href =
        url;


    link.download =
        filename;


    document.body.appendChild(
        link
    );


    link.click();


    document.body.removeChild(
        link
    );


    URL.revokeObjectURL(
        url
    );


}